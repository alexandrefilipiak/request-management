package io.github.alexandrefilipiak.requestmanagement.core.domain;

import jakarta.persistence.*;

import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

import static io.github.alexandrefilipiak.requestmanagement.core.domain.RequestEvent.*;

/**
 * A request going through the lifecycle defined by the state diagram.
 * <p>
 * The state can only change through the event methods of this class, each of
 * which is checked against {@link RequestStateMachine}. There is no setter for
 * the state, so a request can never be put in a state it did not reach through
 * a valid transition.
 */
@Entity
@Table(name = "requests")
public class Request {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String name;

    @Column(nullable = false, columnDefinition = "TEXT")
    private String content;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private RequestState state;

    @Column(length = 1000)
    private String reason;

    @Column(unique = true)
    private Long publicationNumber;

    @OneToMany(mappedBy = "request", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("occurredAt ASC, id ASC")
    private List<StateChange> history = new ArrayList<>();

    @Version
    private long version;

    protected Request() {
        // required by JPA
    }

    private Request(String name, String content) {
        this.name = name;
        this.content = content;
        this.state = RequestState.CREATED;
        record(null, RequestState.CREATED, CREATE, null);
    }

    /**
     * Creates a new request in the {@code CREATED} state.
     *
     * @param name    the name of the request
     * @param content the body of the request
     * @return a new request in the {@code CREATED} state
     */
    public static Request create(String name, String content) {
        return new Request(name, content);
    }

    /**
     * Applies the {@code VERIFY} event to this request.
     * The states in which this is allowed are defined by {@link RequestStateMachine}.
     *
     * @throws InvalidTransitionException if the current state does not allow this event
     */
    public void verify() {
        apply(VERIFY, null);
    }

    /**
     * Applies the {@code ACCEPT} event to this request.
     * The states in which this is allowed are defined by {@link RequestStateMachine}.
     *
     * @throws InvalidTransitionException if the current state does not allow this event
     */
    public void accept() {
        apply(ACCEPT, null);
    }

    /**
     * Applies the {@code REJECT} event to this request. The reason is mandatory
     * and is stored on the request.
     * The states in which this is allowed are defined by {@link RequestStateMachine}.
     *
     * @param reason why the request is rejected; must not be blank
     * @throws ReasonRequiredException    if the reason is null or blank; the state is left unchanged
     * @throws InvalidTransitionException if the current state does not allow this event
     */
    public void reject(String reason) {
        apply(REJECT, reason);
    }

    /**
     * Applies the {@code DELETE} event to this request. The reason is mandatory
     * and is stored on the request; the request itself is not removed.
     * The states in which this is allowed are defined by {@link RequestStateMachine}.
     *
     * @param reason why the request is deleted; must not be blank
     * @throws ReasonRequiredException    if the reason is null or blank; the state is left unchanged
     * @throws InvalidTransitionException if the current state does not allow this event
     */
    public void delete(String reason) {
        apply(DELETE, reason);
    }

    /**
     * Applies the {@code PUBLISH} event to this request and assigns its publication number.
     * The states in which this is allowed are defined by {@link RequestStateMachine}.
     *
     * @param publicationNumber the unique number assigned to the published request;
     *                          generated by the caller, typically from a database sequence
     * @throws InvalidTransitionException if the current state does not allow this event;
     *                                    no number is assigned in that case
     */
    public void publish(long publicationNumber) {
        apply(PUBLISH, null);
        this.publicationNumber = publicationNumber;
    }

    /**
     * Replaces the content. Only allowed while {@link RequestState#isContentEditable()}
     * is true for the current state; the state is not affected.
     *
     * @param content the new body of the request
     * @throws ContentNotEditableException if the current state does not allow editing
     */
    public void updateContent(String content) {
        if (!state.isContentEditable()) {
            throw new ContentNotEditableException(state);
        }
        this.content = content;
    }

    /**
     * Applies an event: checks the reason when the event requires one, moves to the
     * next state according to the state machine, then stores the reason.
     * The reason is checked first so that a failure leaves the state unchanged.
     */
    private void apply(RequestEvent event, String reason) {
        if (event.isReasonRequired() && (reason == null || reason.isBlank())) {
            throw new ReasonRequiredException(event);
        }
        RequestState from = this.state;
        this.state = RequestStateMachine.next(this.state, event);
        if (event.isReasonRequired()) {
            this.reason = reason.trim();
        }
        record(from, this.state, event, event.isReasonRequired() ? reason.trim() : null);
    }

    private void record(RequestState from, RequestState to, RequestEvent event, String reason) {
        history.add(new StateChange(this, from, to, event, reason, Instant.now()));
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getContent() {
        return content;
    }

    public RequestState getState() {
        return state;
    }

    public String getReason() {
        return reason;
    }

    /**
     * @return the publication number, or {@code null} while the request is not published
     */
    public Long getPublicationNumber() {
        return publicationNumber;
    }

    /**
     * @return the history of state changes, oldest first; never empty, the first entry is the creation
     */
    public List<StateChange> getHistory() {
        return Collections.unmodifiableList(history);
    }
}